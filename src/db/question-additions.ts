export function getAdditionalQuestions(topicId: string) {
  const seeds = QUESTIONS[topicId] ?? [];
  const answers = [...new Set(seeds.map(([, answer]) => answer))];
  return seeds.map(([content, answer], index) => {
    const distractors: string[] = [];
    for (let offset = 1; offset < answers.length && distractors.length < 3; offset += 1) {
      const choice = answers[(index + offset) % answers.length];
      if (choice !== answer && !distractors.includes(choice)) distractors.push(choice);
    }
    if (distractors.length !== 3) {
      throw new Error(`Không tạo đủ đáp án nhiễu cho câu hỏi thuộc chuyên đề ${topicId}.`);
    }
    const correctIndex = index % 4;
    const options = [...distractors];
    options.splice(correctIndex, 0, answer);
    return {
      content,
      options,
      correctIndex,
      explanation: `Đáp án đúng là: ${answer}.`,
      difficulty: index < 7 ? "basic" : "advanced",
    };
  });
}
